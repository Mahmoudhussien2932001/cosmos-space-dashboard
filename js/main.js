let currentRecipe = 0;

let currentTab = "tips";


const recipeImage = document.getElementById("recipeImage");

const ratingValue = document.getElementById("ratingValue");

const reviewCount = document.getElementById("reviewCount");

const prepTime = document.getElementById("prepTime");

const cookTime = document.getElementById("cookTime");

const servings = document.getElementById("servings");

const difficultyBadge = document.getElementById("difficultyBadge");

const categoryBadge = document.getElementById("categoryBadge");

const recipeTitle = document.getElementById("recipeTitle");

const recipeSubtitle = document.getElementById("recipeSubtitle");

const tabContent = document.getElementById("tabContent");

const nextRecipeBtn = document.getElementById("nextRecipeBtn");

const tabButtons = document.querySelectorAll(".tab-btn");

function renderRecipe() {
  const recipe = recipes[currentRecipe];

  recipeImage.src = recipe.image;

  recipeImage.alt = recipe.title;

  ratingValue.textContent = recipe.rating;

  reviewCount.textContent = `(${recipe.reviews} reviews)`;

  prepTime.textContent = recipe.prepTime;

  cookTime.textContent = recipe.cookTime;

  servings.textContent = recipe.servings;

  difficultyBadge.textContent = recipe.difficulty;

  categoryBadge.textContent = recipe.category;

  recipeTitle.textContent = recipe.title;

  recipeSubtitle.textContent = recipe.subtitle;

  renderTab();
}

